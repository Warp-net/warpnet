#!/bin/bash
# Writes the WarpnetTransport ProtocolIds from the node's event/paths.go.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WARPFONE_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_DIR="$(cd "${WARPFONE_DIR}/.." && pwd)"

SRC="${REPO_DIR}/event/paths.go"
OUT="${WARPFONE_DIR}/Packages/WarpnetTransport/Sources/WarpnetTransport/ProtocolIds.swift"

{
    echo "// Generated by scripts/generate-protocol-ids.sh from event/paths.go. Do not edit."
    echo
    echo "public enum ProtocolIds {"
    awk '
        /^const \(/ { inside = 1; next }
        inside && /^\)/ { inside = 0 }
        inside && $0 ~ /^[[:space:]]*[A-Z_]+[[:space:]]*=[[:space:]]*"\/[^"]*"/ {
            name = $1
            match($0, /"\/[^"]*"/)
            printf "  public static let %s = %s\n", name, substr($0, RSTART, RLENGTH)
        }
    ' "${SRC}"
    echo "}"
} > "${OUT}"
